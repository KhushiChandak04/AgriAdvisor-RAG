def translate_term(english_term: str, language: str) -> str:
    """Return the term in Hindi/Marathi, or the original if not found."""
    if language == "English":
        return english_term
    lower = english_term.lower()
    for en, trans in GLOSSARY.items():
        if en.lower() == lower:
            return trans.get(language, english_term)
    return english_term
